/* ── 지구본 위의 도시 (b707) ──────────────────────────────────────────
 *
 * 사용자 결정: 「그냥 지구본에 도시정보까지 넣자, 구글지도처럼.」
 *   확대하면 어느 순간 도시 조각이 떠오르고, 그걸 누르면 도시 카드가 뜹니다.
 *   **나라 페이지는 없앴습니다**(ctrymap.js). 화면이 둘이라서 생기던 것들 —
 *   디졸브·이음·뒤로가기 끊김 — 이 통째로 사라집니다.
 *
 * 이 파일이 맡는 것은 «계산»뿐입니다. 그리는 것은 globe.js 가 합니다.
 *   ① map50 파일을 받아 조각(고리)으로 만들기
 *   ② 그 나라 도시로 보로노이 셀 만들기
 *   ③ 둘 다 나라별로 한 번만 하고 들고 있기
 *
 * ⚠⚠ **좌표계는 지도 단위입니다** — `x = (경도+180)/360*1000`,
 *   `y = (90-위도)/180*500`. map50 파일이 이미 그 단위로 적혀 있습니다.
 *   지구본은 이것을 다시 경위도로 풀어 정사도법으로 던집니다.
 * ⚠ **여기서는 cos(위도) 를 «안» 곱합니다.** 그것은 평면 지도(옛 나라 화면)
 *   가 위도에 따라 옆으로 늘어나는 것을 바로잡던 값입니다(b699).
 *   지구본은 정사도법이라 원래 비율이 맞습니다 — 곱하면 오히려 틀립니다.
 */
import { cities } from './cities.js?v=b739';

/* map50 은 `?v=` 를 안 씁니다 — bump.sh 가 199개 파일을 건드리면 배포가
   통째로 무거워집니다. 자료는 안 바뀌므로 제 꼬리표를 따로 답니다. */
const MAP_V = '?m=1';

/* ── 경로 문자열 → 조각 ───────────────────────────────────────────────
   ⚠ map50 은 「M x y l dx dy …Z」 꼴입니다(상대 좌표). 절대로 풀어 담습니다.
   ⚠ 조각마다 상자를 같이 잽니다 — 화면 밖 조각을 건너뛸 때 씁니다. */
export function 조각내기(d){
  const 조각 = [];
  if (!d) return 조각;
  for (const s of String(d).matchAll(/M\s*(-?[\d.]+)[\s,]+(-?[\d.]+)([^M]*)/g)){
    let x = +s[1], y = +s[2];
    const 점 = [[x, y]];
    let x0 = x, x1 = x, y0 = y, y1 = y;
    const 수 = s[3].match(/-?\d*\.?\d+/g) || [];
    for (let i = 0; i + 1 < 수.length; i += 2){
      x += +수[i]; y += +수[i + 1];
      점.push([x, y]);
      if (x < x0) x0 = x; if (x > x1) x1 = x;
      if (y < y0) y0 = y; if (y > y1) y1 = y;
    }
    조각.push({ 점, x0, x1, y0, y1 });
  }
  return 조각;
}

/* ── 보로노이: 「가장 가까운 도시의 땅」 ───────────────────────────────
   한 도시의 땅 = 다른 모든 도시와의 수직이등분선 중 내 쪽 반평면을 다 겹친 것.
   ⚠ 반평면을 계속 자르므로 결과는 **언제나 볼록**입니다 — 오목 다각형
     자르기의 어려움이 없습니다.
   ⚠ 실측(b707): 한국 51도시 0.45ms · 일본 49도시 0.28ms. 한 번만 하면 됩니다. */
function 반평면자르기(poly, a, b, c){
  const out = [];
  const n = poly.length;
  for (let i = 0; i < n; i++){
    const P = poly[i], Q = poly[(i + 1) % n];
    const dp = a * P[0] + b * P[1] - c;
    const dq = a * Q[0] + b * Q[1] - c;
    const p안 = dp <= 1e-9, q안 = dq <= 1e-9;
    if (p안) out.push(P);
    if (p안 !== q안){
      const t = dp / (dp - dq);
      out.push([P[0] + (Q[0] - P[0]) * t, P[1] + (Q[1] - P[1]) * t]);
    }
  }
  return out;
}
export function 보로노이(사이트, 상자){
  const [X0, Y0, X1, Y1] = 상자;
  return 사이트.map((s, i) => {
    let poly = [[X0, Y0], [X1, Y0], [X1, Y1], [X0, Y1]];
    for (let j = 0; j < 사이트.length && poly.length; j++){
      if (j === i) continue;
      const t = 사이트[j];
      const a = t[0] - s[0], b = t[1] - s[1];
      if (a === 0 && b === 0) continue;          /* 좌표가 같은 도시 */
      const c = (t[0] * t[0] + t[1] * t[1] - s[0] * s[0] - s[1] * s[1]) / 2;
      poly = 반평면자르기(poly, a, b, c);
    }
    return poly;
  });
}

/* ── 그 나라 50m 지도 ─────────────────────────────────────────────────
 * ⚠ **한 번 받으면 안 버립니다.** `null` 은 「받아봤는데 없더라」입니다 —
 *   그래야 없는 나라(투발루)에서 매 프레임 다시 시도하지 않습니다.
 * ⚠ **그리는 도중에는 기다릴 수 없습니다.** 그래서 `가진것` 은 «지금 있는
 *   것»만 돌려주고, 없으면 조용히 받아 두기만 합니다. 다음 프레임부터
 *   또렷해집니다 — 그 사이에는 110m 로 그려집니다.
 * ⚠ 같은 나라를 두 번 받지 않게 «받는 중»도 적어 둡니다. */
const 땅캐시 = {};
const 받는중 = {};
export function 가진땅(cc){
  if (땅캐시[cc] !== undefined) return 땅캐시[cc];
  if (!받는중[cc]){
    받는중[cc] = import(`./map50/${cc}.js${MAP_V}`)
      .then(m => { 땅캐시[cc] = 조각내기(m.default); })
      .catch(() => { 땅캐시[cc] = null; })
      .finally(() => { delete 받는중[cc]; });
  }
  return undefined;                    /* 「아직 모름」 */
}

/* ── 그 나라 도시와 보로노이 셀 ───────────────────────────────────────
 * ⚠ `c.cc` 는 속령을 모국으로 접은 값입니다(cities.js) — 괌은 US 로 옵니다.
 *   지도도 US 를 그리므로 그래야 맞습니다.
 * ⚠ **자르는 상자를 넉넉히 잡습니다.** 딱 맞게 자르면 가장자리 도시의 셀이
 *   해안 밖에서 끊겨 바다에 빈틈이 생깁니다.
 * ⚠ 셀은 나라별로 한 번만 만듭니다. 도시 목록이 바뀌는 일은 없습니다. */
const 셀캐시 = {};
export function 나라셀(cc){
  if (셀캐시[cc]) return 셀캐시[cc];
  const 것들 = (cities || []).filter(c =>
    c.cc === cc && (c.center_lat ?? c.lat) != null && (c.center_lng ?? c.lng) != null);
  /* ⚠⚠ **빈 답을 «들고 있지» 않습니다(b712).** ⚠⚠
     `cities` 는 서버에서 받아오는 것이라 앱을 열자마자 «비어 있는» 순간이
     있습니다. 그때 한 번 확대해서 여기까지 오면, 전에는 그 빈 답이 캐시에
     박혀 **자료가 온 뒤에도 그 나라 도시가 영영 안 나왔습니다.**
     확대를 몇 번 하다 보면 도시가 통째로 사라진 것처럼 보이는 것이 이것입니다
     (사용자 신고: 「확대 반복하니까 도시들이 다 사라져버리는」).
   ⚠ 진짜로 도시가 없는 나라(투발루)는 매 프레임 다시 세지만, `filter` 한 번이라
     값이 없습니다. 「받아오는 중」과 「원래 없음」을 여기서는 못 가릅니다. */
  if (!것들.length) return { 도시: [], 셀: [], 상자: [0,0,0,0], 걸침: [1,1,0,0] };
  const 점 = 것들.map(c => [
    ((+(c.center_lng ?? c.lng)) + 180) / 360 * 1000,
    (90 - (+(c.center_lat ?? c.lat))) / 180 * 500,
  ]);
  let x0 = Infinity, x1 = -Infinity, y0 = Infinity, y1 = -Infinity;
  for (const [x, y] of 점){
    if (x < x0) x0 = x; if (x > x1) x1 = x;
    if (y < y0) y0 = y; if (y > y1) y1 = y;
  }
  const 여 = Math.max(x1 - x0, y1 - y0) + 50;
  const 상자 = [x0 - 여, y0 - 여, x1 + 여, y1 + 여];
  const 셀 = 보로노이(점, 상자);
  /* ── 「이 나라가 화면에 걸리나」를 잴 상자(b711·b712) ────────────────
   * ⚠ **자르는 상자(`상자`)를 그대로 쓰면 안 됩니다.** 그것은 나라를 덮으려고
   *   일부러 크게 잡은 것이라(위 `여`), 미국이면 −674~1487 로 **지구를 한 바퀴
   *   넘습니다** — 파리를 들여다봐도 미국이 「걸린다」가 되어 50m 를 받습니다.
   * ⚠ 그렇다고 도시 상자에 딱 맞추면 도시에서 먼 땅(브라질 서부처럼)이
   *   빠집니다. **60 지도단위(약 21°)** 만 넉넉히 둡니다 — 그보다 먼 데까지
   *   도시 칸이 뻗는 나라는 없습니다.
   * ⚠ 전에는 나라 «한가운데 점»으로 걸렀습니다. 러시아처럼 큰 나라는
   *   모스크바를 들여다볼 때 한가운데(시베리아)가 화면 밖이라 **나라째
   *   사라졌습니다** — 그것이 이 상자를 만든 이유입니다. */
  const 여2 = Math.min(여, 60);
  return (셀캐시[cc] = {
    도시: 것들.map((c, i) => ({ c, x: 점[i][0], y: 점[i][1] })),
    셀, 상자,
    걸침: [x0 - 여2, y0 - 여2, x1 + 여2, y1 + 여2],
  });
}

/* 도시가 하나라도 있는 나라인가 — 조각을 받을지 정할 때 씁니다.
   ⚠ 매 프레임 도는 자리라 한 번 세고 들고 있습니다. */
/* ⚠ **비어 있으면 안 들고 있습니다(b712)** — 바로 위 `나라셀` 과 같은 사연입니다.
   자료가 오기 전에 한 번 세어 두면 그 뒤로 영영 「도시 있는 나라가 없다」가 됩니다. */
let 있는나라 = null;
export function 도시있나(cc){
  if (!있는나라 || !있는나라.size){
    const s = new Set();
    for (const c of cities || []) if (c.cc) s.add(c.cc);
    if (!s.size) return false;
    있는나라 = s;
  }
  return 있는나라.has(cc);
}

/* 셀을 상자로 자릅니다 — 보로노이 셀은 나라 전체를 덮을 만큼 크게 만들어
   두는데, 그대로 정사도법에 던지면 «지구 뒤»로 넘어간 꼭짓점이 나옵니다.
   그리기 «직전»에 보이는 창만큼 잘라 두면 그럴 일이 없습니다. */
export function 상자자르기(poly, x0, y0, x1, y1){
  let p = poly;
  p = 반평면자르기(p,  1,  0,  x1);   /*  x <= x1 */
  p = 반평면자르기(p, -1,  0, -x0);   /* -x <= -x0  →  x >= x0 */
  p = 반평면자르기(p,  0,  1,  y1);
  p = 반평면자르기(p,  0, -1, -y0);
  return p;
}
