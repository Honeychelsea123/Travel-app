/* 한 줄로 편 것. 순서는 위 대륙 순서를 그대로 따릅니다. */
export const UN_CODES = Object.values(UN_BY_CONT).flat();

/* ⚠ 총계는 **적지 않고 셉니다.** 195를 손으로 또 적어두면 위 목록을 고칠 때
     둘이 갈라집니다 — 벽은 194칸인데 「/195」라고 적히는 식으로요. */
export const UN_TOTAL = UN_CODES.length;

/* 대륙별 총계도 목록에서 냅니다. map.js 의 `CONT` 와 «같아야» 하고,
   같은지는 아래 `검산()` 이 봅니다. 여기서 따로 적지 않는 이유는 같습니다. */
export const UN_CONT = Object.entries(UN_BY_CONT).map(([k, v]) => [k, v.length]);

/* ── 검산 ───────────────────────────────────────────────────────────
 * 브라우저 콘솔에서 `import('./un.js').then(m => m.검산(CONT))` 로 돌립니다.
 * 자료를 손대면 **반드시** 돌리십시오 — 195라는 수는 여섯 군데에서 쓰이고,
 * 하나만 어긋나도 화면마다 다른 수를 말하게 됩니다. */
export function 검산(CONT){
  const 말 = [];
  if (UN_CODES.length !== 195) 말.push(`전체가 195가 아니라 ${UN_CODES.length}`);
  /* ⚠ 넣고 뺀 것이 맞는지도 봅니다 — 목록이 길어 눈으로는 안 보입니다. */
  if (!UN_CODES.includes('TW')) 말.push('대만(TW)이 빠졌습니다');
  if (UN_CODES.includes('KP'))  말.push('북한(KP)이 남아 있습니다');
  const 겹침 = UN_CODES.filter((c, i) => UN_CODES.indexOf(c) !== i);
  if (겹침.length) 말.push(`두 번 나오는 코드: ${겹침.join(' ')}`);
  const 이상 = UN_CODES.filter(c => !/^[A-Z]{2}$/.test(c));
  if (이상.length) 말.push(`코드 모양이 이상: ${이상.join(' ')}`);
  for (const [이름, 수] of (CONT || [])){
    const 우리 = (UN_BY_CONT[이름] || []).length;
    if (우리 !== 수) 말.push(`${이름} 은 ${수} 이어야 하는데 ${우리}`);
  }
  return 말.length ? 말 : ['맞습니다'];
}
