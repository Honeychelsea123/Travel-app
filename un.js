/* ── UN 195개국 (193 회원국 + 참관국 둘) ─────────────────────────────
 * 「기록 탭 보관함에 깃발들 요거도 하나 만들고 싶은데」(b618, 사용자 요청).
 *
 * ⚠⚠ **왜 새로 적어야 했나** — `cities.js` 의 `countryName` 에는 **88개국**
 *   밖에 없습니다. 그건 「우리 도시 자료가 있는 나라」이지 「세상의 나라」가
 *   아닙니다. 벽은 «안 가본 곳»을 보여주는 것이 반이라, 안 가본 나라를
 *   담고 있지 않은 목록으로는 만들 수가 없습니다.
 *
 * ⚠ **대륙 묶음이 `map.js` 의 `CONT` 와 개수가 같아야 합니다.**
 *   아시아 48 · 유럽 44 · 아프리카 54 · 북아메리카 23 · 남아메리카 12 ·
 *   오세아니아 14 = 195. 홈의 대륙 캐러셀이 그 분모를 쓰므로, 여기서
 *   한 나라라도 다른 대륙에 넣으면 **같은 앱이 두 가지 수를 말합니다.**
 *   아래 `검산()` 이 그것을 셉니다 — 자료를 고치면 반드시 돌리십시오.
 *
 * ⚠ 이름은 안 적습니다. 벽에 필요한 것은 **깃발**뿐이고, 깃발은 나라 코드
 *   두 글자에서 나옵니다(KR → 🇰🇷). 이름까지 195개를 적으면 틀릴 자리가
 *   두 배가 되는데, 정작 이름이 필요한 나라(우리가 도시를 가진 88개국)는
 *   `countryName` 이 이미 갖고 있습니다.
 *
 * ⚠⚠ **깃발 만드는 함수는 여기 두지 않습니다.** `dom.js` 에 `flagOf`·
 *   `flagOk` 가 이미 있습니다(b339 에 거기로 내려둔 것). 처음에 여기에
 *   또 만들었다가 걷었습니다 — 같은 일을 두 곳에서 하면 언젠가 갈라집니다.
 *   **새 함수를 쓰기 전에 `grep` 부터.**
 * ⚠ 코드는 ISO 3166-1 alpha-2 입니다 — `cities` 의 `country` 와 같은 체계라
 *   그대로 맞대볼 수 있습니다. 실제로 맞는지는 아래 `검산()` 이 봅니다.
 *
 * ── 목록을 둘 고쳤습니다 (b653, 사용자 결정) ─────────────────────────
 * ⚠⚠ **대만(TW)을 넣고 북한(KP)을 뺐습니다.** 그래서 아시아는 여전히 48,
 *   합계도 여전히 195입니다 — **분모를 쓰는 여섯 군데를 안 건드려도
 *   됩니다**(map.js 의 `UN_COUNTRIES`·`CONT` 포함). 우연히 맞은 것이므로
 *   다음에 목록을 고칠 때는 반드시 `검산(CONT)` 을 돌리십시오.
 *
 * **대만** — UN 회원국은 아니지만 여행앱은 거의 다 별개로 셉니다
 *   (NomadMania · Been · Polarsteps · TripIt 은 ISO 3166-1 을 그대로
 *   씁니다). 한국인 방문 5위 나라(연 110만)가 깃발 벽에서 빠지면
 *   실사용에서 손해가 큽니다. 우리 목록은 **「UN 195」가 아니라 「여행앱이
 *   세는 나라」**입니다 — 이름만 UN 을 빌려 쓴 것으로 읽지 마십시오.
 * **북한** — 사용자 결정으로 뺐습니다. 도시도 같이 지웁니다(db/077). */

