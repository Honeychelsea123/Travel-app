-- =====================================================================
-- 도시 유명도 (fame) 1~3
--
-- 성향 카드가 "남들이 안 가는 도시 매니아" 같은 판정을 하려면
-- 도시가 얼마나 알려진 곳인지 알아야 합니다. 별점만으로는 알 수 없습니다.
--
--   1  누구나 아는 곳          도쿄 · 파리 · 방콕 · 뉴욕
--   2  여행 좀 다니면 아는 곳  피렌체 · 가나자와 · 포르투 · 다낭
--   3  덜 알려진 곳            인스브루크 · 할슈타트 · 컨딩 · 베오그라드
--
-- **한국인 기준입니다.** 다낭 · 세부 · 보라카이는 여기서 1등급인데
-- 서양 기준으로는 2~3등급입니다. 이 앱을 쓰는 사람이 한국 사람이라
-- 그쪽 감각에 맞춰야 "남들이 안 가는 곳"이라는 말이 맞아떨어집니다.
--
-- 312곳 전부에 매겼습니다. 1등급 77 · 2등급 120 · 3등급 115.
-- 여러 번 실행해도 안전합니다.
-- =====================================================================

alter table public.cities add column if not exists fame smallint
  check (fame is null or fame between 1 and 3);

comment on column public.cities.fame is
  '유명도 1(누구나 아는 곳) ~ 3(덜 알려진 곳). 한국인 기준. 성향 카드 판정에 씀';

