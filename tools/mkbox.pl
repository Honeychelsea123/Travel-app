binmode STDOUT, ':encoding(UTF-8)';

# ── 주·도 파일의 «먼 땅» 상자 (b797) ─────────────────────────────────────
#
# 왜: globe.js 는 주·도(adm1)를 «화면에 걸린 나라»만 받습니다(b797 — 전에는 도시 상자에 21°를
#   더한 하나로 재서, 이탈리아를 한 번 들여다봤는데 82개 · 4.5MB 를 받았습니다). «걸렸나»는
#   110m 고리 상자와 도시 둘레로 잽니다. 그런데 **110m 에 없는 먼 땅**(아조레스 · 카나리아 ·
#   레위니옹 · 갈라파고스 · 알류샨 · 스발바르 …)은 거기 안 걸려서, 그 섬만 들여다보면 그 나라를
#   안 받아 **섬이 안 그려졌습니다**(재 봄: 40개국 · 도시가 있으면 도시 둘레가 살림).
# 무엇을: 주·도 고리 가운데 110m 고리 상자(+1.5) 밖에 있는 것을 나라별로 모아, 가까운 것끼리
#   (2 지도단위 ≈ 0.7° 안) 묶어 상자로 적습니다 → adm1/_box.js. globe.js 가 110m 상자와 같이 봅니다.
#
# 쓰는 법:  perl tools/mkbox.pl        (저장소 뿌리에서. world.js · adm1/*.js 를 읽습니다)
# ⚠ world.js 나 adm1/*.js 를 바꾸면 **다시 돌리고** citymap.js 의 MAP_V 를 올리십시오.
# ⚠ `%딸린땅` 은 citymap.js 의 `딸린땅` 과 같게 둘 것(모국 파일과 같이 받는 속령).

my %딸린땅 = (US => ['GU', 'MP'], FR => ['PF']);
my $해안여유 = 1.5;    # globe.js `해안여유` 와 같게
my $묶음거리 = 2;      # 이만큼 가까운 섬은 한 상자로
my $작은것 = 0.05;     # 가로+세로가 이보다 작은 고리(2km 남짓)는 뺍니다 — 확대해도 점입니다

sub 읽기 { my $f = shift; open my $h, '<:raw', $f or return undef; local $/; my $s = <$h>; close $h; $s }
# 「M x y l dx dy … Z」 → 고리마다 [x0, y0, x1, y1]
sub 상자들 {
  my $d = shift; my @b;
  for my $sub (split /(?=M)/, $d){
    my @n = $sub =~ /-?(?:\d+\.?\d*|\.\d+)/g; next unless @n >= 2;
    my ($x, $y) = ($n[0], $n[1]); my ($x0, $y0, $x1, $y1) = ($x, $y, $x, $y);
    for (my $i = 2; $i + 1 < @n; $i += 2){
      $x += $n[$i]; $y += $n[$i+1];
      $x0 = $x if $x < $x0; $x1 = $x if $x > $x1; $y0 = $y if $y < $y0; $y1 = $y if $y > $y1;
    }
    push @b, [$x0, $y0, $x1, $y1];
  }
  @b;
}
sub 겹침 { my ($a, $b, $여) = @_;
  for my $s (0, 1000, -1000){
    return 1 if $a->[0] <= $b->[2] + $여 + $s && $a->[2] >= $b->[0] - $여 + $s
             && $a->[1] <= $b->[3] + $여 && $a->[3] >= $b->[1] - $여;
  }
  0 }

my $w = 읽기('world.js') or die "world.js 를 못 읽었습니다(저장소 뿌리에서 돌리십시오)\n";
my %글; my %차례;
while ($w =~ /<path data-c="([A-Z]{2})" d="([^"]*)"/g){ $글{$1} .= $2; $차례{$1} //= scalar keys %차례 }

my %결과; my ($모두, $먼) = (0, 0);
for my $cc (sort { $차례{$a} <=> $차례{$b} } keys %글){
  my @바탕 = map { [$_->[0] - $해안여유, $_->[1] - $해안여유, $_->[2] + $해안여유, $_->[3] + $해안여유] } 상자들($글{$cc});
  my @먼땅;
  for my $f ($cc, @{ $딸린땅{$cc} || [] }){
    my $s = 읽기("adm1/$f.js") // next;
    while ($s =~ /"(M[^"]*)"/g){
      for my $b (상자들($1)){
        $모두++;
        next if ($b->[2] - $b->[0]) + ($b->[3] - $b->[1]) < $작은것;
        next if grep { 겹침($b, $_, 0) } @바탕;
        push @먼땅, [@$b]; $먼++;
      }
    }
  }
  next unless @먼땅;
  # 가까운 것끼리 묶습니다(더 안 묶일 때까지)
  my @묶 = @먼땅;
  my $또 = 1;
  while ($또){
    $또 = 0;
    OUTER: for my $i (0 .. $#묶){
      for my $j ($i + 1 .. $#묶){
        next unless 겹침($묶[$i], $묶[$j], $묶음거리);
        # 날짜변경선을 넘겨 묶지는 않습니다(넘으면 상자가 지구를 덮습니다)
        next if abs(($묶[$i][0] + $묶[$i][2]) - ($묶[$j][0] + $묶[$j][2])) > 1000;
        my ($a, $b) = ($묶[$i], $묶[$j]);
        $묶[$i] = [ ($a->[0] < $b->[0] ? $a->[0] : $b->[0]), ($a->[1] < $b->[1] ? $a->[1] : $b->[1]),
                    ($a->[2] > $b->[2] ? $a->[2] : $b->[2]), ($a->[3] > $b->[3] ? $a->[3] : $b->[3]) ];
        splice @묶, $j, 1; $또 = 1; last OUTER;
      }
    }
  }
  # 소수 한 자리 — 바깥으로 둥글립니다(작아지지 않게)
  $결과{$cc} = [ map { [ int($_->[0] * 10 - 1) / 10, int($_->[1] * 10 - 1) / 10,
                         int($_->[2] * 10 + 1) / 10, int($_->[3] * 10 + 1) / 10 ] } @묶 ];
}

my $글 = "/* 주·도 파일의 «먼 땅» 상자 — tools/mkbox.pl 이 world.js · adm1/*.js 에서 구운 것(b797).\n"
       . "   110m 고리 상자 밖의 섬을 나라별로 묶은 것입니다. globe.js 가 «화면에 걸렸나» 를 잴 때 씁니다.\n"
       . "   손으로 고치지 마십시오 — world.js 나 adm1 을 바꾸면 다시 굽고 citymap.js 의 MAP_V 를 올리십시오. */\n"
       . "export default {\n"
       . join(",\n", map { my $cc = $_; "\"$cc\":[" . join(',', map { '[' . join(',', @$_) . ']' } @{$결과{$cc}}) . ']' }
                     sort { $차례{$a} <=> $차례{$b} } keys %결과)
       . "\n};\n";
open my $o, '>:encoding(UTF-8)', 'adm1/_box.js' or die "adm1/_box.js: $!\n"; print $o $글; close $o;
my $상자수 = 0; $상자수 += @{$결과{$_}} for keys %결과;
printf "나라 %d · 주·도 고리 %d 중 먼 땅 %d → 상자 %d · %.1fKB\n", scalar keys %결과, $모두, $먼, $상자수, length($글) / 1024;
